-- LICH_SU_QUYET_TOAN
CREATE TABLE LICH_SU_QUYET_TOAN (
    MA_QUYET_TOAN NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MA_SU_KIEN NUMBER NOT NULL,
    MA_TAI_KHOAN_NHAN NUMBER NOT NULL,
    SO_TIEN_QUYET_TOAN NUMBER(18, 2) NOT NULL,
    THOI_DIEM_QUYET_TOAN TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    TRANG_THAI VARCHAR2(50) DEFAULT 'Thành công',
    NOI_DUNG VARCHAR2(255),
    CONSTRAINT FK_QT_SK FOREIGN KEY (MA_SU_KIEN) REFERENCES SU_KIEN(MA_SU_KIEN),
    CONSTRAINT FK_QT_TK FOREIGN KEY (MA_TAI_KHOAN_NHAN) REFERENCES TAI_KHOAN(MA_TAI_KHOAN)
);

-- NHAT_KY_THONG_BAO
CREATE TABLE NHAT_KY_THONG_BAO (
    MA_THONG_BAO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MA_TAI_KHOAN NUMBER,
    EMAIL_NHAN VARCHAR2(100) NOT NULL,
    TIEU_DE VARCHAR2(200) NOT NULL,
    NOI_DUNG CLOB,
    THOI_DIEM_GUI TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    TRANG_THAI VARCHAR2(50) DEFAULT 'Thành công',
    LOAI_THONG_BAO VARCHAR2(50),
    CONSTRAINT FK_NTB_TK FOREIGN KEY (MA_TAI_KHOAN) REFERENCES TAI_KHOAN(MA_TAI_KHOAN)
);
