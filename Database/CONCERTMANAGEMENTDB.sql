-- TRG_DON_MUA_COMPOUND_UPDATEGHE
CREATE OR REPLACE TRIGGER TRG_DON_MUA_COMPOUND_UPDATEGHE
FOR UPDATE OF TrangThaiThanhToan ON DON_MUA
COMPOUND TRIGGER
    TYPE t_donmua_list IS TABLE OF DON_MUA.MaDonMua%TYPE;
    v_danh_sach_don t_donmua_list := t_donmua_list();
    BEFORE EACH ROW IS
    BEGIN
        IF (:NEW.TrangThaiThanhToan IN (N'Đã hủy', N'Đã hết hạn'))
           AND (:OLD.TrangThaiThanhToan NOT IN (N'Đã hủy', N'Đã hết hạn')) THEN

            v_danh_sach_don.EXTEND;
            v_danh_sach_don(v_danh_sach_don.LAST) := :NEW.MaDonMua;
        END IF;
    END BEFORE EACH ROW;
    AFTER STATEMENT IS
    BEGIN
        IF v_danh_sach_don.COUNT > 0 THEN
            FOR i IN 1 .. v_danh_sach_don.COUNT LOOP
                UPDATE TRANG_THAI_GHE_THEO_SUAT
                SET TrangThai = N'Còn trống'
                WHERE (MaGhe, MaLichDien) IN (
                    SELECT MaGhe, MaLichDien
                    FROM VE
                    WHERE MaDonMua = v_danh_sach_don(i)
                ) AND TrangThai IN (N'Đang giữ chỗ', N'Đã đặt');
            END LOOP;

            v_danh_sach_don.DELETE;
        END IF;
    END AFTER STATEMENT;

END TRG_DON_MUA_COMPOUND_UPDATEGHE;
