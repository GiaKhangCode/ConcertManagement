CREATE OR REPLACE TRIGGER TRG_KHU_VUC_COMPOUND_SUC_CHUA
FOR INSERT OR UPDATE OF SucChuaKV, MaHangVe ON KHU_VUC
COMPOUND TRIGGER
    TYPE t_events IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
    v_events t_events;

    BEFORE EACH ROW IS
        v_masukien NUMBER;
    BEGIN
        SELECT MaSuKien INTO v_masukien FROM HANG_VE WHERE MaHangVe = :NEW.MaHangVe;
        v_events(v_masukien) := 1;
    END BEFORE EACH ROW;

    AFTER STATEMENT IS
        v_id_sukien NUMBER;
        v_suc_chua_dd NUMBER;
        v_tong_kv NUMBER;
    BEGIN
        v_id_sukien := v_events.FIRST;
        WHILE v_id_sukien IS NOT NULL LOOP
            SELECT DD.SucChua INTO v_suc_chua_dd
            FROM SU_KIEN SK JOIN DIA_DIEM DD ON SK.MaDiaDiem = DD.MaDiaDiem
            WHERE SK.MaSuKien = v_id_sukien;

            SELECT NVL(SUM(SucChuaKV), 0) INTO v_tong_kv
            FROM KHU_VUC K JOIN HANG_VE H ON K.MaHangVe = H.MaHangVe
            WHERE H.MaSuKien = v_id_sukien;

            IF v_tong_kv > v_suc_chua_dd THEN
                 RAISE_APPLICATION_ERROR(-20033, N'LỖI: Vượt quá sức chứa!');
            END IF;

            v_id_sukien := v_events.NEXT(v_id_sukien);
        END LOOP;
    END AFTER STATEMENT;

END TRG_KHU_VUC_COMPOUND_SUC_CHUA;
