    v_GiamToiDa   MA_GIAM_GIA.GiamToiDa%TYPE;
BEGIN
    SELECT LoaiGiam, SoLuongGiam, GiamToiDa
    INTO v_LoaiGiam, v_SoLuongGiam, v_GiamToiDa
    FROM MA_GIAM_GIA
    WHERE MaGiamGia = p_MaGiamGia; -- Thêm dấu ;

    IF v_LoaiGiam = N'Theo phần trăm' THEN
        -- Dùng LEAST thay vì MIN để lấy giá trị nhỏ hơn giữa mức giảm tối đa và số tiền % tính ra
        RETURN LEAST(v_GiamToiDa, p_TongTien * (v_SoLuongGiam / 100));
    ELSE
        RETURN LEAST(v_SoLuongGiam, p_TongTien);
    END IF;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20044, 'Lỗi: Không tìm thấy mã giảm giá');
        RETURN 0;
    WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(-20045, 'Lỗi hệ thống trong quá trình tính tiền giảm giá: ' || SQLERRM);
        RETURN 0;
END;
/

CREATE OR REPLACE FUNCTION FN_Kiem_Tra_Quyen_TK (
    p_MaTaiKhoan IN TAI_KHOAN.MaTaiKhoan%TYPE,
    p_MaChucNang IN CHUC_NANG.MaChucNang%TYPE,
    p_HanhDong   IN VARCHAR2 -- Nhận các giá trị: 'THEM', 'SUA', 'XOA', 'XEM', 'XUATFILE'
) RETURN NUMBER
AS
    v_CoQuyen NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_CoQuyen
    FROM PHAM_VI_QUYEN pv
    WHERE pv.MaChucNang = p_MaChucNang
      -- 1. Kiểm tra hành động người dùng yêu cầu có được phép (bằng 1) trong phạm vi quyền này không
      AND (
           (UPPER(p_HanhDong) = 'THEM' AND pv.Them = 1) OR
           (UPPER(p_HanhDong) = 'SUA' AND pv.Sua = 1) OR
           (UPPER(p_HanhDong) = 'XOA' AND pv.Xoa = 1) OR
           (UPPER(p_HanhDong) = 'XEM' AND pv.Xem = 1) OR
           (UPPER(p_HanhDong) = 'XUATFILE' AND pv.XuatFile = 1)
      )
      -- 2. Kiểm tra xem phạm vi quyền này có được gắn với người dùng qua đường trực tiếp hoặc qua nhóm không
      AND (
           -- Con đường A: Quyền được cấp trực tiếp cho tài khoản
           EXISTS (
               SELECT 1
               FROM PHAN_QUYEN_TAI_KHOAN pqt
               WHERE pqt.MaPhamVi = pv.MaPhamVi
                 AND pqt.MaTaiKhoan = p_MaTaiKhoan
           )
           OR
           -- Con đường B: Quyền được cấp thông qua nhóm quyền
           EXISTS (
               SELECT 1
               FROM CAU_HINH_NHOM_QUYEN ch
               JOIN PHAN_QUYEN_NHOM pqn ON ch.MaNhomQuyen = pqn.MaNhomQuyen
               WHERE ch.MaPhamVi = pv.MaPhamVi
                 AND pqn.MaTaiKhoan = p_MaTaiKhoan
           )
      );

    -- Nếu tìm thấy ít nhất 1 dòng thỏa mãn (từ nhóm hoặc trực tiếp), trả về 1 (Cho phép)
    IF v_CoQuyen > 0 THEN
        RETURN 1;
    ELSE
        RETURN 0;
    END IF;

EXCEPTION
    WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(-20046, 'Lỗi hệ thống khi kiểm tra phân quyền: ' || SQLERRM);
        RETURN 0;
END;
/

