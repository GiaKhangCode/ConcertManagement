CREATE OR REPLACE FUNCTION FN_KiemTraGheTrong(
    p_MaGhe IN GHE_NGOI.MaGhe%TYPE,
    p_MaLichDien IN LICH_DIEN.MaLichDien%TYPE
)
RETURN NUMBER
AS
    v_Check_TonTai INT := 0;
    v_Check_GheTrong INT := 0;
BEGIN

    IF p_MaGhe IS NULL OR p_MaLichDien IS NULL THEN
        RAISE_APPLICATION_ERROR(-20052, N'Lỗi hệ thống: Mã ghế và mã lịch diễn không được để trống.');
    END IF;

    SELECT COUNT(*) INTO v_Check_TonTai
    FROM TRANG_THAI_GHE_THEO_SUAT
    WHERE MaGhe = p_MaGhe AND MaLichDien = p_MaLichDien;

    IF v_Check_TonTai = 0 THEN
         RAISE_APPLICATION_ERROR(-20053, N'Dữ liệu nhập vào không hợp lệ: Không tìm thấy thông tin ghế có ID [' || p_MaGhe || N'] cho lịch diễn có ID [' || p_MaLichDien || N'].');
    END IF;

    SELECT COUNT(*) INTO v_Check_GheTrong
    FROM TRANG_THAI_GHE_THEO_SUAT
    WHERE MaGhe = p_MaGhe AND MaLichDien = p_MaLichDien AND TrangThai = N'Còn trống';

    IF v_Check_GheTrong <> 0 THEN
        RETURN 1;
    ELSE
        RETURN 0;
    END IF;
END;
/

CREATE OR REPLACE FUNCTION FN_TinhSoDuVi(
    p_MaVi VI_CA_NHAN.MAVI%type
) RETURN NUMBER AS
    v_SoDuHienTai NUMBER;
BEGIN
    SELECT NVL(SUM(
               CASE
                   WHEN LoaiBienDong = N'Tăng' THEN SoTien
                   WHEN LoaiBienDong = N'Giảm' THEN -SoTien
               END
               ), 0) INTO v_SoDuHienTai
    FROM LICH_SU_BIEN_DONG_VI
    WHERE MaVi = p_MaVi;
    RETURN v_SoDuHienTai;
end;
