CREATE OR REPLACE TRIGGER TRG_HANG_VE_BU_TINHTONGTIEN
    BEFORE UPDATE OF GiaNiemYet ON HANG_VE
    FOR EACH ROW
BEGIN
    PKG_BAO_MAT_DON_MUA.g_ChoPhepUpdate := TRUE;
    IF :NEW.GiaNiemYet <> :OLD.GiaNiemYet THEN
        FOR rec IN (
            SELECT MaDonMua, COUNT(*) as SoLuong
            FROM VE
            WHERE MaHangVe = :NEW.MaHangVe
            GROUP BY MaDonMua
        )
        LOOP
            UPDATE DON_MUA
            SET TongTien = TongTien + (:NEW.GiaNiemYet - :OLD.GiaNiemYet) * rec.SoLuong
            WHERE MaDonMua = rec.MaDonMua;
        END LOOP;
    END IF;
    PKG_BAO_MAT_DON_MUA.g_ChoPhepUpdate := FALSE;
EXCEPTION
    WHEN OTHERS THEN
        PKG_BAO_MAT_DON_MUA.g_ChoPhepUpdate := FALSE;
        RAISE;
END;
