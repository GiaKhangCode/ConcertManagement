CREATE OR REPLACE FUNCTION FN_KiemTraGioiHanMuaVe(
    p_MaTaiKhoan TAI_KHOAN.MaTaiKhoan%TYPE,
    p_MaHangVe HANG_VE.MaHangVe%TYPE,
    p_SoVeDinhMua NUMBER
)
RETURN NUMBER
AS
    v_GioiHan HANG_VE.GioiHanMoiNguoi%TYPE;
    v_SoVeDaMua NUMBER;
BEGIN
    IF p_MaTaiKhoan IS NULL OR p_MaHangVe IS NULL THEN
        RAISE_APPLICATION_ERROR(-20054, N'Lỗi hệ thống: Mã tài khoản và mã hạng vé không được để trống.');
    END IF;

    SELECT GioiHanMoiNguoi INTO v_GioiHan
    FROM HANG_VE
    WHERE MaHangVe = p_MaHangVe;

    SELECT COUNT(MaVe) INTO v_SoVeDaMua
    FROM DON_MUA DM
    JOIN VE V
    ON DM.MaDonMua = V.MaDonMua
    WHERE DM.MaTaiKhoan = p_MaTaiKhoan AND V.MaHangVe = p_MaHangVe AND TrangThaiThanhToan IN ('Chờ thanh toán', 'Đã thanh toán');

    IF p_SoVeDinhMua + v_SoVeDaMua > v_GioiHan THEN
        RETURN 0;
    ELSE
        RETURN 1;
    END IF;
END;
/

