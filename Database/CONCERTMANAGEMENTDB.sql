);

-- 2. Người dùng
CREATE TABLE NGUOI_DUNG
(
    MaNguoiDung   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    HoTen         NVARCHAR2(255)       NOT NULL,
