CREATE OR REPLACE PROCEDURE SP_GIAI_PHONG_GHE (
    p_SoPhutHetHan IN NUMBER DEFAULT 10, -- Mặc định là 10 phút, có thể truyền tham số khác
    p_KetQua       OUT NVARCHAR2
)
IS
    -- Định nghĩa Cursor tìm các đơn hàng quá hạn và Khóa chúng lại.
    -- Kỹ thuật SKIP LOCKED giúp lờ đi các đơn hàng đang bị khóa bởi giao dịch thanh toán khác
    CURSOR cur_DonMuaQuaHan IS
        SELECT MaDonMua
        FROM DON_MUA
        WHERE TrangThaiThanhToan = N'Chờ thanh toán'
          AND ThoiDiemMua <= CURRENT_TIMESTAMP - NUMTODSINTERVAL(p_SoPhutHetHan, 'MINUTE')
        FOR UPDATE SKIP LOCKED;

    v_Count NUMBER := 0;
BEGIN
    -- Mở vòng lặp duyệt qua từng đơn hàng quá hạn tìm được
    FOR rec IN cur_DonMuaQuaHan LOOP

        -- 1. Giải phóng Ghế: Đưa trạng thái từ 'Đang giữ chỗ' về lại 'Còn trống'
        UPDATE TRANG_THAI_GHE_THEO_SUAT tt
        SET TrangThai = N'Còn trống'
        WHERE EXISTS (
            SELECT 1 FROM VE v
            WHERE v.MaDonMua = rec.MaDonMua
              AND v.MaGhe = tt.MaGhe
              AND v.MaLichDien = tt.MaLichDien
        );

        -- 2. Hủy Vé: Đổi vé từ 'Chờ thanh toán' sang 'Đã hủy'
        UPDATE VE
        SET TrangThaiVe = N'Đã hủy'
        WHERE MaDonMua = rec.MaDonMua;

        -- 3. Hủy Đơn Mua: Chuyển trạng thái đơn thành 'Đã hết hạn'
        UPDATE DON_MUA
        SET TrangThaiThanhToan = N'Đã hết hạn'
        WHERE CURRENT OF cur_DonMuaQuaHan; -- Cập nhật chính xác dòng đang được Cursor trỏ tới

        v_Count := v_Count + 1;
    END LOOP;

    -- Chốt toàn bộ thay đổi
    COMMIT;

    IF v_Count > 0 THEN
        p_KetQua := N'Thành công: Đã dọn dẹp và giải phóng ghế cho ' || v_Count || N' đơn hàng quá hạn.';
    ELSE
        p_KetQua := N'Hệ thống sạch sẽ: Không có đơn hàng nào quá hạn cần giải phóng.';
    END IF;

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        p_KetQua := N'Lỗi hệ thống khi dọn dẹp ghế: ' || SQLERRM;
END;
/

CREATE OR REPLACE PROCEDURE SP_DANG_KY_TAI_KHOAN (
    p_HoTen        IN NGUOI_DUNG.HoTen%Type,
    p_Email        IN NGUOI_DUNG.Email%type,
    p_SoDienThoai  IN NGUOI_DUNG.SoDienThoai%type,
    p_TenDangNhap  IN TAI_KHOAN.TenDangNhap%type,
    p_MatKhauMaHoa IN TAI_KHOAN.MatKhauMaHoa%type,

    --- Output
    p_KetQua       OUT NVARCHAR2
)
IS
    v_MaNguoiDung NGUOI_DUNG.MaNguoiDung%TYPE;
    v_MaTaiKhoan  NUMBER;
    v_Count       NUMBER;
BEGIN
    -- 1. Kiểm tra các dữ liệu UNIQUE bằng COUNT (Dành cho các luồng xử lý thông thường)
    SELECT COUNT(*) INTO v_Count FROM NGUOI_DUNG WHERE Email = p_Email;
    IF v_Count > 0 THEN
        p_KetQua := N'Lỗi: Email này đã được đăng ký.';
        RETURN;
    END IF;

    SELECT COUNT(*) INTO v_Count FROM NGUOI_DUNG WHERE SoDienThoai = p_SoDienThoai;
    IF v_Count > 0 THEN
        p_KetQua := N'Lỗi: Số điện thoại này đã được đăng ký.';
        RETURN;
    END IF;

    SELECT COUNT(*) INTO v_Count FROM TAI_KHOAN WHERE TenDangNhap = p_TenDangNhap;
    IF v_Count > 0 THEN
        p_KetQua := N'Lỗi: Tên đăng nhập đã tồn tại. Vui lòng chọn tên khác.';
        RETURN;
    END IF;

    -- 2. Insert dữ liệu
    INSERT INTO NGUOI_DUNG (HoTen, Email, SoDienThoai)
    VALUES (p_HoTen, p_Email, p_SoDienThoai)
    RETURNING MaNguoiDung INTO v_MaNguoiDung;

    INSERT INTO TAI_KHOAN (MaNguoiDung, TenDangNhap, MatKhauMaHoa)
    VALUES (v_MaNguoiDung, p_TenDangNhap, p_MatKhauMaHoa)
    RETURNING MaTaiKhoan INTO v_MaTaiKhoan;

    -- Giả sử ID nhóm quyền "Khách hàng" là 1
    INSERT INTO PHAN_QUYEN_NHOM (MaTaiKhoan, MaNhomQuyen)
    VALUES (v_MaTaiKhoan, 1);

    INSERT INTO VI_CA_NHAN (MaTaiKhoan, SoDu, MatKhauThanhToan)
    VALUES (v_MaTaiKhoan, 0, p_MatKhauMaHoa);

    -- 4. Hoàn tất
    COMMIT;
    p_KetQua := N'Thành công';

EXCEPTION
    -- Bắt lỗi Race Condition (Nếu 2 request lọt qua vòng COUNT cùng lúc)
    WHEN DUP_VAL_ON_INDEX THEN
        ROLLBACK;
        p_KetQua := N'Lỗi: Thông tin (Email, SĐT hoặc Tên đăng nhập) đã tồn tại trong hệ thống do có giao dịch đồng thời.';

    WHEN OTHERS THEN
        ROLLBACK;
        p_KetQua := N'Lỗi hệ thống: ' || SQLERRM;
END;
/

-- Thanh toán bằng ví cá nhân
CREATE OR REPLACE PROCEDURE SP_THANH_TOAN_VI (
    p_MaDonMua IN DON_MUA.MaDonMua%type,
    p_MaTaiKhoan IN TAI_KHOAN.MaTaiKhoan%type,
    p_MaKhauThanhToan IN VI_CA_NHAN.MatKhauThanhToan%type,

    p_KetQua OUT NVARCHAR2
)
IS
    v_SoDu VI_CA_NHAN.SODU%type;
    v_MaVi VI_CA_NHAN.MAVI%type;
    v_MaGiaoDich GIAO_DICH.MaGiaoDich%type;
    v_TongTienThanhToan DON_MUA.TongTien%type;

BEGIN
    -- 1. Lấy thông tin để so sánh kiểm tra
    -- Lấy thông tin mã ví, số dư
    -- (Trường hợp sai mật khẩu hay sao đó thì văng xuống expception)
    SELECT Mavi, SoDu INTO v_MaVi, v_SoDu
    FROM VI_CA_NHAN V
    WHERE V.MaTaiKhoan = p_MaTaiKhoan AND V.MatKhauThanhToan = p_MaKhauThanhToan;

    -- Lấy tổng tiền của đơn mua từ mã đơn mua đầu vào
    SELECT TongTien INTO v_TongTienThanhToan
    FROM DON_MUA DM
    WHERE DM.MaDonMua = p_MaDonMua AND TrangThaiThanhToan = 'Chờ thanh toán';

    -- 2 Kiểm tra số dư để xử lý thanh toán, cập nhật trạng thái cho các bảng
    IF v_SoDU >= v_TongTienThanhToan THEN

        -- Cập nhật số dư ví cá nhân
        UPDATE VI_CA_NHAN
        SET SoDu = SoDu - v_TongTienThanhToan
        WHERE MaVi = v_MaVi;

        -- Cập nhật trạng thái Đơn mua
        UPDATE DON_MUA
        SET TrangThaiThanhToan = N'Đã thanh toán',
            PhuongThucThanhToan = N'Ví cá nhân'
        WHERE MaDonMua = p_MaDonMua;

        -- Cập nhật trạng thái vé
        UPDATE VE
        SET VE.TRANGTHAIVE = N'Hiệu Lực'
        WHERE MaDonMua = p_MaDonMua;

        -- Cập nhật trạng thái giao dịch
        UPDATE GIAO_DICH
        SET TRANGTHAI = N'Thành Công'
        WHERE MaDonMua = p_MaDonMua AND TRANGTHAI = N'Chờ thanh toán'
        RETURNING MaGiaoDich INTO v_MaGiaoDich; -- Lấy mã giao dịch liên quan

        -- Ghi lại lịch sử biến động ví
        INSERT INTO LICH_SU_BIEN_DONG_VI (MAVI,MaGiaoDichLienQuan, LoaiBienDong, SOTIEN, NOIDUNG)
        VALUES(v_MaVi, v_MaGiaoDich, N'Giảm',v_TongTienThanhToan, '* Thanh Toán đơn mua ' || p_MaDonMua ||' *');

        p_KetQua := N'Thanh toán thành công !!';
        COMMIT;

    ELSE
        p_KetQua := N'Không đủ tiền trong ví cá nhân, thanh toán Thất Bại !!';
        ROLLBACK ;
    END IF;

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        p_KetQua := N'Lỗi: Sai mật khẩu ví, hoặc đơn mua không tồn tại /đã được thanh toán !!';
        ROLLBACK ;
    WHEN OTHERS THEN
        p_KetQua := N'Lỗi hệ thống: ' || SQLERRM;
        ROLLBACK ;
end;
/

CREATE OR REPLACE PROCEDURE SP_XAC_NHAN_TT_NGOAI (
    p_MaDonMua          IN DON_MUA.MaDonMua%TYPE,
    p_MaGiaoDichCongTT  IN GIAO_DICH.MaGiaoDichCongTT%TYPE,
    p_SoTienThucNhan    IN GIAO_DICH.SoTien%TYPE,
    p_PhuongThuc        IN DON_MUA.PhuongThucThanhToan%TYPE,
    p_TrangThaiGiaoDich IN GIAO_DICH.TrangThai%TYPE,
    p_MaLoi             IN GIAO_DICH.MaLoi%TYPE,
    p_DuLieuPhanHoi     IN GIAO_DICH.DuLieuPhanHoi%TYPE,

    -- OUTPUT
    p_KetQua            OUT NVARCHAR2
)
IS
    v_TongTienDon  DON_MUA.TongTien%TYPE;
    v_TrangThaiDon DON_MUA.TrangThaiThanhToan%TYPE;

    RESOURCE_BUSY EXCEPTION;
    PRAGMA EXCEPTION_INIT(RESOURCE_BUSY, -54);
BEGIN
    -- 1. KHÓA ĐƠN MUA (Chống Double Call)
    -- Giả sử MoMo gặp lag và bắn 2 request "Thành công" về server cùng lúc,
    -- thằng nào đến trước sẽ khóa dòng này, thằng đến sau sẽ văng lỗi RESOURCE_BUSY.
    SELECT TongTien, TrangThaiThanhToan INTO v_TongTienDon, v_TrangThaiDon
    FROM DON_MUA
    WHERE MaDonMua = p_MaDonMua
    FOR UPDATE NOWAIT;

    -- 2. KIỂM TRA TRẠNG THÁI HIỆN TẠI
    IF v_TrangThaiDon = N'Đã thanh toán' THEN
        ROLLBACK;
        p_KetQua := N'Bỏ qua: Đơn hàng này đã được xác nhận thanh toán trước đó.';
        RETURN;
    END IF;

    IF v_TrangThaiDon <> N'Chờ thanh toán' THEN
        ROLLBACK;
        p_KetQua := N'Thất bại: Đơn hàng đang ở trạng thái không hợp lệ (' || v_TrangThaiDon || ').';
        RETURN;
    END IF;

    -- 3. BẢO MẬT: CHỐNG GIAN LẬN SỐ TIỀN
    -- Hacker có thể đánh chặn request từ MoMo về Server và sửa số tiền. Ta phải check chéo!
    IF p_TrangThaiGiaoDich = N'Thành công' AND p_SoTienThucNhan <> v_TongTienDon THEN
        -- Tùy chọn: Gọi SP_LOG_LOI_GIAO_DICH() ở đây nếu muốn lưu vết hacker
        ROLLBACK;
        p_KetQua := N'CẢNH BÁO GIAN LẬN: Số tiền cổng thanh toán báo về không khớp với hóa đơn hệ thống!';
        RETURN;
    END IF;

    -- 4. GHI LOG GIAO DỊCH
    INSERT INTO GIAO_DICH (MaDonMua, MaGiaoDichCongTT, SoTien, TrangThai, MaLoi, DuLieuPhanHoi, ThoiGianTao)
    VALUES (p_MaDonMua, p_MaGiaoDichCongTT, p_SoTienThucNhan, p_TrangThaiGiaoDich, p_MaLoi, p_DuLieuPhanHoi, CURRENT_TIMESTAMP);

    -- 5. CHỐT ĐƠN & XUẤT VÉ (Chỉ làm khi Thành công)
    IF p_TrangThaiGiaoDich = N'Thành công' THEN

        -- Cập nhật Đơn Mua
        UPDATE DON_MUA
        SET TrangThaiThanhToan = N'Đã thanh toán', PhuongThucThanhToan = p_PhuongThuc
        WHERE MaDonMua = p_MaDonMua;

        -- Kích hoạt Vé
        UPDATE VE
        SET TrangThaiVe = N'Hiệu lực', ThoiGianDaBan = CURRENT_TIMESTAMP
        WHERE MaDonMua = p_MaDonMua;

        -- Chốt Ghế (Chuyển 'Đang giữ chỗ' -> 'Đã đặt')
        UPDATE TRANG_THAI_GHE_THEO_SUAT tt
        SET TrangThai = N'Đã đặt'
        WHERE EXISTS (
            SELECT 1 FROM VE v
            WHERE v.MaDonMua = p_MaDonMua
              AND v.MaGhe = tt.MaGhe
              AND v.MaLichDien = tt.MaLichDien
        );

        p_KetQua := N'Xác nhận Webhook: Thanh toán thành công, đã xuất vé!';

    ELSE
        -- Nếu giao dịch thất bại từ cổng (Khách hủy, hết tiền trong thẻ...)
        -- Ta ghi log xong thì thôi, để kệ đó cho Job tự động hủy đơn sau 10 phút.
        p_KetQua := N'Xác nhận Webhook: Ghi nhận giao dịch thất bại từ cổng thanh toán.';
    END IF;

    -- Giải phóng khóa và chốt dữ liệu
    COMMIT;

EXCEPTION
    WHEN RESOURCE_BUSY THEN
        ROLLBACK;
        p_KetQua := N'Thất bại: Đơn hàng đang được một luồng Webhook khác xử lý.';
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        p_KetQua := N'Thất bại: Không tìm thấy đơn mua số ' || p_MaDonMua;
    WHEN OTHERS THEN
        ROLLBACK;
        p_KetQua := N'Lỗi hệ thống: ' || SQLERRM;
END;
/

